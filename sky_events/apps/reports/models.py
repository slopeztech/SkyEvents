class RequirementStatus(models.TextChoices):
    PENDING = "pending", _("Pending")
    FULFILLED = "fulfilled", _("Fulfilled")
    CANCELLED = "cancelled", _("Cancelled")


def _attachment_upload_to(instance: "ReportAttachment", filename: str) -> str:
    """Store uploaded attachments under media/attachments/{requirement_id}/{filename}."""
    import os  # noqa: PLC0415

    safe_name = os.path.basename(filename)
    return f"attachments/{instance.requirement_id}/{safe_name}"


class MediaRequirement(TimeStampedModel):
    """
    A request from an admin for specific local files from a station.

    The station script polls GET /api/v1/station/requirements/ to discover
    pending requirements, then fulfils each one by uploading the files via
    POST /api/v1/station/requirements/{id}/media/.

    When all ``requested_paths`` have been uploaded the status is
    automatically set to ``fulfilled``.
    """

    station = models.ForeignKey(
        Station,
        on_delete=models.CASCADE,
        related_name="media_requirements",
        verbose_name=_("station"),
    )
    requested_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name="created_requirements",
        verbose_name=_("requested by"),
    )
    requested_paths = models.JSONField(
        _("requested paths"),
        default=list,
        help_text=_("List of local file paths on the station to be uploaded."),
    )
    status = models.CharField(
        _("status"),
        max_length=16,
        choices=RequirementStatus.choices,
        default=RequirementStatus.PENDING,
        db_index=True,
    )
    notes = models.TextField(
        _("notes"),
        blank=True,
        help_text=_("Admin notes about what these files are needed for."),
    )
    expires_at = models.DateTimeField(
        _("expires at"),
        null=True,
        blank=True,
        help_text=_("Optional deadline after which the requirement is no longer served to the script."),
    )

    class Meta:
        verbose_name = _("media requirement")
        verbose_name_plural = _("media requirements")
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"Requirement #{self.pk} [{self.status}] — {self.station.code}"


class ReportAttachment(TimeStampedModel):
    """
    A media file uploaded by a station script to fulfil a MediaRequirement.

    The actual file is written to Django MEDIA_ROOT; only metadata is stored
    in the remaining fields.
    """

    requirement = models.ForeignKey(
        MediaRequirement,
        on_delete=models.CASCADE,
        related_name="attachments",
        verbose_name=_("requirement"),
    )
    file = models.FileField(
        _("file"),
        upload_to=_attachment_upload_to,
        help_text=_("Uploaded media file from the station."),
    )
    original_path = models.CharField(
        _("original path"),
        max_length=1024,
        help_text=_("Local file path on the station storage."),
    )
    file_type = models.CharField(
        _("file type"),
        max_length=20,
        choices=FileType.choices,
        default=FileType.OTHER,
        db_index=True,
    )
    file_size_bytes = models.PositiveBigIntegerField(
        _("file size (bytes)"),
        null=True,
        blank=True,
    )
    uploaded_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name="uploaded_attachments",
        verbose_name=_("uploaded by"),
    )

    class Meta:
        verbose_name = _("report attachment")
        verbose_name_plural = _("report attachments")
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"Attachment [{self.get_file_type_display()}] — {self.original_path}"
